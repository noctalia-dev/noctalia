  DisplayBackendSpec mangoSpec(compositors::mango::MangoRuntime& runtime) {
    const auto reload = [&runtime]() { (void)runtime.dispatch("reload_config"); };
    return DisplayBackendSpec{
        .kind = "mango",
        .supportsHdr = true,
        .fetchArgs = []() { return std::vector<std::string>{}; },
        .parseFetch = [](std::string_view /*payload*/, std::string& error) { return readRules(error); },
        .composeAll = [reload](const std::map<std::string, OutputState>& target) -> std::vector<DisplayCommand> {
          std::string error;
          (void)writeRules(target, error);
          if (!error.empty()) {
            kLog.warn("{}", error);
          }
          return {DisplayCommand{{}, std::nullopt, reload}};
        },
        .composePositions = [reload](const std::map<std::string, OutputState>& target) -> std::vector<DisplayCommand> {
          std::string error;
          (void)writeRules(target, error);
          if (!error.empty()) {
            kLog.warn("{}", error);
          }
          return {DisplayCommand{{}, std::nullopt, reload}};
        },
    };
  }

