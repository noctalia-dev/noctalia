  // Queue policy for a callback invocation.
  struct ScriptCallOptions {
    // A newer queued call on the same coalescing stream replaces this one.
    bool coalesce = false;
    // This call may be dropped when the queue is full.
    bool droppable = false;
    // Coalescing stream this call belongs to; empty means the callback name.
    // Callbacks whose relative order matters (a graph's pointer position and
    // its pointer leave) share one key so the newest event always wins.
    std::string coalesceKey;
  };

  struct ScriptEvent {
    ScriptEventKind kind = ScriptEventKind::Update;
    std::uint64_t generation = 0;
    std::uint64_t hostId = 0;
    std::string functionName;
    std::string chunkName;
    std::string source;
    // StreamLine / HttpStreamLine payload.
    std::string first;
    // CallArgs payload: the callback's argument list, pushed in order.
    ScriptArgs args;
    bool processMatchResult = false;
    // When true, a newer CallArgs event on the same coalescing stream supersedes
    // this one while it is still queued (only the latest payload matters, e.g.
    // onAudioSpectrum frames). IPC and other callbacks leave this false so every
    // event is delivered.
    bool coalesce = false;
    // Coalescing stream identity, defaulted to the callback name.
    std::string coalesceKey;
    // When true, this event may be dropped to make room once the queue is full
    // (state-echo callbacks such as onHover, where a missed edge is harmless).
    bool droppable = false;
    int callbackRef = 0;
    process::RunResult commandResult;
    // AsyncFileResult payload.
    bool fileOk = false;
    std::string fileData;
    std::string fileError;
    // AsyncHttpResult / HttpStreamClosed payload.
    bool httpOk = false;
    bool httpIsDownload = false;
    int httpStatus = 0;
    std::string httpBody;
    // SoundLoadResult payload.
    bool soundLoadOk = false;
    std::string soundLoadError;
    // ColorPickerResult payload (nil on cancellation).
    std::optional<std::string> colorPickerResult;
    // UmbrielActionResult payload (nullopt when the action was accepted).
    std::optional<std::string> umbrielActionError;
    // StateWatchResult payload (the changed value as JSON).
    std::string stateJson;
    // IdleWatchResult payload: true on idled, false on resumed.
    bool idle = false;
    // NightLightWatchResult payload: the current night-light snapshot.
    ScriptNightLightState nightLightState;
    // CompositorEvent payload: the event name and its data (null for "reset").
    std::string compositorEvent;
    std::shared_ptr<const compositors::CompositorEventPayload> compositorEventData;
    // Stop payload: SIGINT/SIGTERM for signal-driven process shutdown, otherwise 0.
    int exitSignal = 0;
    // Stop payload: identifies why the runtime is being destroyed.
    ScriptExitReason exitReason = ScriptExitReason::Reload;
    // SettingsChanged payload: the new seeded settings snapshot to swap in, or nullopt
    // when only a shell config value read via getSetting changed.
    std::optional<ScriptSettings> newSettings;
    ScriptSnapshot snapshot;
    std::chrono::milliseconds budget{12};
  };

  struct ScriptResult {
    std::uint64_t generation = 0;
    ScriptPatch patch;
    std::vector<ScriptSideEffect> sideEffects;
    // One-shot host request. Unlike ScriptPatch this is never merged into the
    // runtime replay state and therefore cannot reopen after a late subscribe.
    std::optional<ScriptContextMenuRequest> contextMenuRequest;
    bool ok = true;
    bool timedOut = false;
    bool hasOnIpc = false;
    bool hasOnIpcKnown = false;
    bool modulePathsKnown = false;
    std::vector<std::filesystem::path> modulePaths;
    bool unhealthy = false;
    // True when this result included a CopyToClipboard side effect (before dispatch).
    bool copiedToClipboard = false;
    std::string callbackName;
    std::string error;
  };

